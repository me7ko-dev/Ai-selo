// Какво мисли всеки жител по темите от задачите — зависи от слуховете, които знае, и на кого вярва.
import type { VillagerId } from '../data/villagers';
import type { VillagerState, WorldState } from './types';
import { hpick } from './text';

export type ClueTopic = 'chickens' | 'goats' | 'lamia';

/** Най-силната вяра на жителя в слух с даден етикет (−1..1; 0 = не е чувал). */
export function beliefIn(state: WorldState, v: VillagerState, tag: string): number {
  let best = 0;
  for (const r of state.rumors) {
    if (r.tag !== tag) continue;
    const b = v.rumorBelief?.[String(r.id)];
    if (b !== undefined && Math.abs(b) > Math.abs(best)) best = b;
  }
  return best;
}

function trustsPlayer(v: VillagerState, aff: number, trust: number): boolean {
  const r = v.relations.player; return !!r && r.affinity >= aff && r.trust >= trust;
}

export function clueText(state: WorldState, v: VillagerState, topic: ClueTopic): string {
  const id = v.id as VillagerId;
  const f = state.flags;
  const day = Math.floor(state.time / 1440) + 1;
  const vary = <T>(arr: readonly T[]) => hpick(arr, id, topic, day);
  if (topic === 'chickens') return chickens(state, v, id, vary);
  if (topic === 'goats') return goats(state, v, id, vary);
  return lamia(state, v, id, vary, !!f.lamia_dead);
}

function chickens(state: WorldState, v: VillagerState, id: VillagerId, vary: <T>(a: readonly T[]) => T): string {
  const f = state.flags;
  const lost = Number(f.chickens_lost ?? 3);
  const fox = beliefIn(state, v, 'fox'), petko = beliefIn(state, v, 'petko_thief');
  if (f.fox_caught) {
    const done: Record<VillagerId, string> = {
      gena: 'Казах ли ти, чедо? Звяр е било, не човек. Сега кокошките на Радка спят спокойно.',
      peyu: 'Аз като кмет обявявам случая за приключен! Лисицата-таласъм е хваната и редът е възстановен.',
      petko: 'Абе, видяхте ли? Звяр е бил! А всички мене гледаха накриво…',
      ivan: 'Хм. Значи не е бил Петко. Сгрешил съм.',
      maria: 'Лисица-таласъм! Представи си — истинска приказка, а се случи точно при нас.',
      radka: 'Ох, най-сетне! Проклетата лисица я няма. Ама да си остане между нас — на Петко още му се сърдя малко.',
      kalin: 'Аз само така… радвам се, че вече никой не обвинява Петко. Не беше честно.',
    };
    return done[id];
  }
  switch (id) {
    case 'radka':
      if (f.radka_admitted || trustsPlayer(v, 25, 35))
        return 'Ама да си остане между нас… Видях я с очите си — лисица, ама не обикновена: очите ѝ светят като въглени и идва откъм Тъмната гора. Никой нямаше да ми повярва, затова виках по Петко.';
      return vary([
        `Петко е, кой друг! Вечно се мотае около кокошарника с тая негова гега. Вече ${lost} кокошки ми липсват!`,
        `Чу ли? Пак ми изчезна кокошка — вече ${lost}! Петко е, казвам ти. Има очи на крадец.`,
        'Не ме питай, че ще кипна! Петко ги краде, знам аз. Ама кой ще ми повярва…',
      ]);
    case 'gena':
      if (fox >= 0.4)
        return 'Чедо, хора кокошки не крадат така. Намерих малки следи от лапи край кокошарника — светеха на зазоряване като гнили дънери. Към гората водеха.';
      return 'Не вярвай на всичко, което Радка разправя, мари. Иди виж следите край кокошарника, ама рано сутрин, преди да ги стъпчат.';
    case 'kalin':
      if (fox >= 0.3)
        return 'Аз само така, между другото… Една нощ, като работех до късно, видях синкава светлинка да се промъква от кокошарника към гората. Не съм казвал на никого — кой ли ще ме слуша.';
      return 'Ако не ти преча… Не мисля, че е Петко. Той си обича животните, не би посегнал на чужди.';
    case 'ivan':
      if (petko >= 0.4 && petko >= fox) return vary(['Хм. Петко е. Козите му в нивата ми, кокошките на Радка — все той.', 'Петко. Кой друг. Думата ми е дума.']);
      if (fox >= 0.3) return 'Хм. Баба Гена казва, че е звяр от гората. Може би. Нощем не излизам да проверя.';
      return 'Хм. Не знам. Не съм видял.';
    case 'petko':
      if (fox >= 0.3) return 'Абе, звяр е това, не човек! Чух, че имало следи като от лисица, ама светели. Само Радка да не ме гледа накриво!';
      return vary([
        'Кво?! Аз да крада кокошки? Тая Радка ще я… Кажи ѝ да си гледа кокошарника, а не мене!',
        'Абе ти пък какво се бъркаш? Не съм пипал ничии кокошки. Ми то е ясно — Радка ме мрази.',
      ]);
    case 'maria':
      if (fox >= 0.2) return 'Радка вижда крадци навсякъде. А баба Гена говори за някакви светещи следи към гората. Аз бих повярвала на Гена.';
      if (petko > 0.5) return 'Може и да е Петко… макар че не ми се вярва. Попитай баба Гена — тя чете следите по-добре от всеки.';
      return 'Радка разправя, че е Петко, но тя не го обича — как да ѝ вярваш? Попитай баба Гена, тя чете следите по-добре от всеки.';
    case 'peyu':
      if (fox >= 0.4 && fox > petko) return 'Аз като кмет чух за някакъв звяр от гората. Едно време таласъмите не смееха да припарят в селото!';
      if (petko >= 0.3) return 'Аз като кмет съм наясно — Петко е. Но редът си е ред: без доказателства не мога да го съдя.';
      return 'Аз като кмет ще разследвам този случай лично. Редът си е ред! Но засега… никой нищо не е видял.';
  }
}

function goats(state: WorldState, v: VillagerState, id: VillagerId, vary: <T>(a: readonly T[]) => T): string {
  const f = state.flags;
  const day = Math.floor(state.time / 1440) + 1;
  if (f.ivan_petko_peace) {
    const peace: Record<VillagerId, string> = {
      gena: 'Иван и Петко се сдобриха, чедо. Ей го на — и козите вече знаят къде им е мястото.',
      peyu: 'Аз като кмет винаги съм казвал, че двамата ще се сдобрят. Редът е възстановен!',
      petko: 'Абе, сдобрихме се с Иван. Козите вече не влизат в нивата. Доволен ли си?',
      ivan: 'Хм. С Петко вече сме добре. Думата ми е дума.',
      maria: 'Иван и Петко пак си говорят! Не вярвах, че ще доживея да ги видя на една маса.',
      radka: 'Чу ли? Иван и Петко седнаха заедно в хана! Цялото село говори.',
      kalin: 'Аз само така… направих им нова ограда за нивата. Никой не попита кой.',
    };
    return peace[id];
  }
  const fresh = f.goats_day === day || f.goats_day === day - 1;
  switch (id) {
    case 'ivan':
      return fresh ? 'Хм. Днес пак. Козите на Петко ми изпасаха половината ечемик. Още веднъж — и ще говорим другояче.'
        : 'Козите на Петко пак ми тъпчат нивата. Не е случайно. Хм.';
    case 'petko':
      if (trustsPlayer(v, 30, 40)) return 'Абе… добре де. Аз ги пускам. От яд — Иван ме гледа отвисоко, както и всички. Ама на никого не казвай.';
      return vary(['Козите си ходят, където искат. Кво съм виновен, че нивата на Иван е най-сладка?', 'Абе стига с тая нива! Коза е — не знае чие е.']);
    case 'radka':
      return 'Чу ли? Козите на Петко пак били в нивата на Иван. Ама да си остане между нас — мисля, че Петко нарочно ги пуска.';
    case 'gena':
      return 'Двамата са като огън и барут, чедо. Петко е обиден на целия свят, а Иван мълчи, докато не кипне. Някой трябва да ги сдобри.';
    case 'peyu':
      return 'Аз като кмет съм им казвал сто пъти — редът си е ред! Нивата си е нива, кошарата — кошара.';
    case 'maria':
      return 'Жал ми е за Иван — цяла година работи тая нива. Но и Петко не е лош, само е самотен.';
    case 'kalin':
      return 'Ако не ти преча… Мога да направя нова ограда на нивата. Само че никой не ме е питал.';
  }
}

function lamia(state: WorldState, v: VillagerState, id: VillagerId, vary: <T>(a: readonly T[]) => T, dead: boolean): string {
  if (dead) {
    const joy: Record<VillagerId, string> = {
      gena: 'Чуваш ли, чедо? Бистрица пак пее под моста. Така пееше, когато бях млада.',
      peyu: 'Аз като кмет ще наредя да ти издигнат паметник! Е, поне камък с името ти. Реката тече!',
      petko: 'Абе, овцете пият до насита. Казах, че ще ти дам най-хубавото агне — думата ми е дума.',
      ivan: 'Хм. Ти я уби. Аз не бих посмял. Благодаря.',
      maria: 'Ламята е мъртва, а реката тече! Ще ти изтъка черга с три змейови глави — да се помни.',
      radka: 'Чу ли? Цялото село говори само за теб! Ела в хана — днес ядеш без пари.',
      kalin: 'Аз само така… знаех си, че ще стане точно ти.',
    };
    return joy[id];
  }
  const afraid = v.mood.startsWith('уплаш');
  switch (id) {
    case 'gena': return 'Ламята спи на извора под Ламин връх и пие водата на Бистрица. Три глави има, чедо — всяка със свой нрав. Пази се от средната.';
    case 'peyu': return 'Откакто Ламята седна на извора, Бистрица пресъхна. Аз като кмет не спя по цели нощи — без вода нивите ще умрат.';
    case 'petko': return 'Абе, овцете нямат вода. Ако някой убие тая змия, ще му дам най-хубавото агне.';
    case 'ivan': return afraid ? 'Хм. Не ми говори за нея. Нощем я сънувам.' : 'Хм. Ламята. С добра сабя и малко смелост… Ще видим.';
    case 'maria': return 'Казват, че Ламята има три глави и пази извора. Представи си — истинска приказка, а ние живеем в нея!';
    case 'radka': return vary(['Чу ли? Казват, че Ламята изяла последния, който тръгнал към върха! Ама може и да лъжат…', 'Ама да си остане между нас — Ламята се бои от огън. Така разправяше баба ми.']);
    case 'kalin': return 'Аз само така… Казват, че Ламята не обича огъня и добре опънатия лък.';
  }
}
